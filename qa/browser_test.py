from playwright.sync_api import sync_playwright
from pathlib import Path
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:8081')
    page.get_by_role('heading',name='Khám phá sách').wait_for()
    assert page.locator('.card').count()==8
    page.screenshot(path='qa/reader.png',full_page=True)
    page.get_by_role('button',name='Đăng nhập',exact=True).click()
    page.get_by_label('Email',exact=True).fill('reader@demo.local')
    page.get_by_label('Mật khẩu',exact=True).fill('ThuVienDemo2026!')
    page.locator('#auth').get_by_role('button',name='Đăng nhập',exact=True).click()
    page.get_by_role('button',name='Phiếu mượn của tôi').wait_for()
    page.locator('[data-book="2"]').click()
    page.locator('dialog').get_by_role('button',name='Đặt mượn',exact=True).click()
    page.locator('dialog').wait_for(state='hidden')
    page.get_by_role('button',name='Phiếu mượn của tôi').click()
    page.get_by_text('Cơ sở dữ liệu quan hệ',exact=False).wait_for()
    assert 'Chờ nhận sách' in page.locator('tbody').inner_text()
    page.get_by_role('button',name='Đăng xuất').click()
    page.get_by_role('button',name='Đăng nhập',exact=True).click()
    page.get_by_label('Email',exact=True).fill('librarian@demo.local')
    page.get_by_label('Mật khẩu',exact=True).fill('ThuVienDemo2026!')
    page.locator('#auth').get_by_role('button',name='Đăng nhập',exact=True).click()
    page.get_by_role('heading',name='Tổng quan thư viện').wait_for()
    page.get_by_role('button',name='Giao & nhận trả',exact=False).first.click()
    page.locator('[data-op="handover"]').first.click()
    page.locator('dialog').get_by_role('button',name='Xác nhận').click()
    page.locator('dialog').wait_for(state='hidden')
    page.locator('[data-op="return"]').first.wait_for()
    page.screenshot(path='qa/staff.png',full_page=True)
    page.locator('[data-op="return"]').first.click()
    page.locator('dialog').get_by_role('button',name='Xác nhận').click()
    page.locator('dialog').wait_for(state='hidden')
    page.get_by_role('button',name='Quản lý đầu sách').click()
    page.get_by_role('button',name='+ Thêm đầu sách').click()
    page.get_by_label('Tên sách',exact=True).fill('Sách kiểm thử giao diện')
    page.locator('#book-form').get_by_role('button',name='Tạo đầu sách').click()
    page.get_by_role('button',name='Quản lý bản sách / mã vạch').wait_for()
    page.get_by_role('button',name='Quản lý bản sách / mã vạch').click()
    page.get_by_label('Mã vạch mới').fill('UI-TEST-001')
    page.get_by_role('button',name='+ Thêm bản').click()
    page.get_by_role('cell',name='UI-TEST-001',exact=True).wait_for()
    page.get_by_role('button',name='Đóng',exact=True).click()
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_role('button',name='Tra cứu sách').click()
    page.get_by_role('heading',name='Khám phá sách').wait_for()
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    page.screenshot(path='qa/mobile.png',full_page=True)
    assert not errors, errors
    print('PASS: catalog, reader login, reserve, loan display, logout, librarian login, handover, return, book creation, copy creation, mobile overflow, no JS errors')
    browser.close()
